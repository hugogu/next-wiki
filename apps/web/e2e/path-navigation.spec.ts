import { test, expect } from '@playwright/test';
import { clickSignInSubmit } from './test-helpers';

test('switches navigation mode, follows breadcrumbs and virtual folders, and retains the preference', async ({ page, browser, request }) => {
  const base = `path-navigation-${Date.now()}`;
  await page.goto('/auth/login');
  await page.getByLabel('Email').fill('admin@example.com');
  await page.getByLabel('Password').fill('admin123');
  await clickSignInSubmit(page);
  await page.waitForURL('/');
  const create = async (path: string, title: string, slug = path) => {
    const response = await page.request.post('/api/v1/pages', { data: { path, title, slug } });
    expect(response.status()).toBe(201);
    const { id } = await response.json();
    expect((await page.request.post(`/api/v1/pages/${id}/revisions/1/publication`, { data: {} })).ok()).toBe(true);
  };
  await create(base, 'Navigation section', `${base}-address`);
  await create(`${base}/child`, 'Direct child');
  await create(`${base}/folder/deep`, 'Deep child');
  await create(`${base}-outside`, 'Outside branch');
  await page.goto('/user-center/settings');
  await page.getByLabel('Navigation mode', { exact: true }).selectOption('current');
  await expect(page.getByRole('status')).toHaveText('Navigation mode saved.');
  await page.goto(`/wiki/${base}-address`);
  const sidebar = page.locator('aside nav');
  await expect(sidebar.getByRole('link', { name: 'Direct child', exact: true })).toBeVisible();
  await expect(sidebar.getByRole('link', { name: 'Outside branch' })).toHaveCount(0);
  await expect(sidebar.getByRole('link', { name: 'Deep child' })).toHaveCount(0);
  await sidebar.getByRole('link', { name: 'folder', exact: true }).click();
  await expect(page).toHaveURL(`/pages/browse/wiki/${base}/folder`);
  await expect(sidebar.getByRole('link', { name: 'Deep child', exact: true })).toBeVisible();
  await sidebar.getByRole('link', { name: 'Deep child', exact: true }).click();
  await expect(page.getByRole('navigation', { name: 'Breadcrumbs' }).getByText('Default', { exact: true })).toHaveCount(0);
  const crumbs = page.getByRole('navigation', { name: 'Breadcrumbs' });
  await expect(crumbs.getByRole('link', { name: 'Wiki', exact: true })).toHaveAttribute('href', '/pages/browse/wiki');
  await expect(crumbs.getByRole('link', { name: 'Navigation section', exact: true })).toHaveAttribute('href', `/wiki/${base}-address`);
  await expect(crumbs.getByRole('link', { name: 'folder', exact: true })).toHaveAttribute('href', `/pages/browse/wiki/${base}/folder`);
  await crumbs.getByRole('link', { name: 'Navigation section', exact: true }).click();
  await expect(page).toHaveURL(`/wiki/${base}-address`);
  await page.goBack();
  await expect(crumbs.getByRole('link', { name: 'folder', exact: true })).toBeVisible();
  await page.reload();
  await expect(sidebar.getByText('No child pages in this directory.')).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(crumbs.getByRole('link', { name: 'Wiki', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await expect(page.locator('aside')).not.toBeInViewport();
  await page.screenshot({ path: test.info().outputPath('navigation-mobile.png'), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`/wiki/${base}-address`);
  await page.screenshot({ path: test.info().outputPath('navigation-desktop.png'), fullPage: true });
  const freshContext = await browser.newContext();
  const freshPage = await freshContext.newPage();
  await freshPage.goto('/auth/login');
  await freshPage.getByLabel('Email').fill('admin@example.com');
  await freshPage.getByLabel('Password').fill('admin123');
  await clickSignInSubmit(freshPage);
  await freshPage.waitForURL('/');
  await freshPage.goto('/user-center/settings');
  await expect(freshPage.getByLabel('Navigation mode', { exact: true })).toHaveValue('current');
  await freshPage.close();
  await freshContext.close();
  await page.goto('/user-center/settings');
  await page.getByLabel('Navigation mode', { exact: true }).selectOption('tree');
  await expect(page.getByRole('status')).toHaveText('Navigation mode saved.');
  await page.goto(`/wiki/${base}-address`);
  await expect(sidebar.getByRole('link', { name: 'Outside branch', exact: true })).toBeVisible();
  await sidebar.getByRole('button', { name: base, exact: true }).click();
  await expect(sidebar.getByRole('link', { name: 'Direct child', exact: true })).toBeVisible();
  const anonymous = await request.get(`/api/v1/navigation?path=${base}&status=all`);
  expect(anonymous.headers()['cache-control']).toBe('private, no-store');
  expect((await anonymous.json()).root.children).toHaveLength(2);
});
